export type Dictionary = DeepStringify<typeof en>;
export type TranslationKey = Paths<typeof en>;

// Amplía los literales de `en` (as const) a `string`, para que `es` (y otros
// idiomas futuros) no estén forzados a repetir el texto inglés exacto.
type DeepStringify<T> = {
  [K in keyof T]: T[K] extends string ? string : DeepStringify<T[K]>;
};

// Tipo recursivo que produce las claves anidadas separadas por `.` (p. ej.
// `"auth.login.title"`). Las hojas de tipo `string` (y arrays) cierran el camino.
type Paths<T, P extends string = ""> = {
  [K in keyof T]-?: T[K] extends string
    ? `${P}${P extends "" ? "" : "."}${K & string}`
    : T[K] extends readonly unknown[]
      ? `${P}${P extends "" ? "" : "."}${K & string}`
      : Paths<T[K], `${P}${P extends "" ? "" : "."}${K & string}`>;
}[keyof T];

